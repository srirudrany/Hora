    kt_list(tithi, lambda t: f"TithiInfo({q(t['iast'])}, {q(t['paksha'])}, {t['number']}, {q(t['family'])}, {q(t['dev'])}, {q(t['good'])})"),
    kt_list(nak, lambda n: f"NakshatraInfo({q(n['iast'])}, {q(n['dev'])}, {q(n['ta'])}, {q(n['nature'])}, {q(n['deity'])}, {q(n['temper'])})"),
    kt_list(yoga, lambda y: f"YogaInfo({q(y['iast'])}, {q(y['dev'])}, {str(y['shubha']).lower()}, {q(y['nature'])})"),
    kt_list(kinfo.values(), lambda k: f"KaranaInfo({q(k['iast'])}, {q(k['dev'])}, {str(k['fixed']).lower()}, {q(k['animal'])}, {q(k['nature'])}, {q(k['use'])})"),
    ", ".join(map(str, karana_order)),
    kt_list(vara, lambda v: f"VaraInfo({q(v['iast'])}, {q(v['ta'])}, {q(v['lord'])}, {q(v['dev'])}, {q(v['en'])}, {q(v['nature'])})"),
    kt_list(rasi, lambda r: f"RasiInfo({q(r['iast'])}, {q(r['dev'])}, {q(r['month'])}, {q(r['monthTa'])})"),
    ", ".join(q(s) for s in samvat),
    ", ".join(q(s) for s in hora),
    ", ".join(map(str, kala["rahu_kalam"])), ", ".join(map(str, kala["yamagandam"])), ", ".join(map(str, kala["kulikai"])),
    kt_list(nature_uses.items(), lambda kv: f"{q(kv[0])} to NatureInfo({q(kv[1]['meaning'])}, {q(kv[1]['uses'])})"),
    kt_list(fest, lambda f: f"Festival({q(f['name'])}, {f['month']}, {f['star']})"),
