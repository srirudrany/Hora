    kt_list(glossary.items(), lambda kv: f"{q(kv[0])} to {q(kv[1])}"),
    kt_list(grahas, lambda g: f"Graha({q(g['key'])}, {q(g['iast'])}, {q(g['english'])}, {q(g['science'])}, {q(g['lore'])})"),
