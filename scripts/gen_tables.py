#!/usr/bin/env python3
"""Generate the native name tables (Kotlin + Swift) from the repo's single sources of truth.

Sources:
  data/sky.json      - graha descriptions and clock-ring legend colours
  data/glossary.json - glossary one-liners
  data/names.json  - IAST / Tamil / Devanagari names, natures, rasi <-> Tamil month (Hora)
  data/rules.json  - muhurta rules, festivals
  docs/SPEC.md §3  - Devanagari names, deities, temperaments, yoga natures, karana symbols

Run from the repo root:  python3 scripts/gen_tables.py
Outputs:
  android/core/src/main/kotlin/org/hora/panchanga/core/Tables.kt
  ios/PanchangaCore/Sources/PanchangaCore/Tables.swift
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
names = json.load(open(os.path.join(ROOT, "data/names.json"), encoding="utf-8"))
rules = json.load(open(os.path.join(ROOT, "data/rules.json"), encoding="utf-8"))
glossary = json.load(open(os.path.join(ROOT, "data/glossary.json"), encoding="utf-8"))
sky = json.load(open(os.path.join(ROOT, "data/sky.json"), encoding="utf-8"))
spec = open(os.path.join(ROOT, "docs/SPEC.md"), encoding="utf-8").read()


def spec_table(heading):
    """Rows of the first markdown table after a heading line (cells stripped of ** markup)."""
    i = spec.index(heading)
    rows = []
    for line in spec[i:].splitlines()[1:]:
        if line.startswith("|"):
            cells = [c.strip().replace("**", "") for c in line.strip().strip("|").split("|")]
            if set(cells[0]) <= set("-: "):
                continue
            rows.append(cells)
        elif rows:
            break
    return rows[1:]  # drop header


tithi_spec = spec_table("## 1. Tithi Table (30 entries)")
nak_spec = spec_table("## 2. Nakshatra Table (27 entries)")
yoga_spec = spec_table("## 3. Yoga Table (27 entries)")
kar_spec = spec_table("## 4. Karana Table (60 entries)")
vara_spec = spec_table("## 5. Vara Table (7-day Weekday)")
assert len(tithi_spec) == 30 and len(nak_spec) == 27 and len(yoga_spec) == 27
assert len(kar_spec) == 60 and len(vara_spec) == 7

ASUBHA = {1, 6, 9, 10, 13, 15, 17, 19, 27}
for r in yoga_spec:  # cross-check SPEC classification against CLAUDE.md
    assert (r[3] == "Ashubha") == (int(r[0]) in ASUBHA), r

tithi = [dict(iast=t["name"], paksha=t["paksha"], number=t["number"], family=t["family"],
              dev=tithi_spec[i][1], good=tithi_spec[i][5]) for i, t in enumerate(names["tithi"])]
nak = [dict(iast=n["iast"], dev=n["devanagari"], ta=n["tamil"], nature=n["nature"],
            deity=nak_spec[i][5], temper=nak_spec[i][6]) for i, n in enumerate(names["nakshatra"])]
yoga = [dict(iast=y["iast"], dev=yoga_spec[i][1], shubha=(i + 1) not in ASUBHA, nature=yoga_spec[i][4])
        for i, y in enumerate(names["yoga"])]
order = names["karana"]["order_by_index"]
assert len(order) == 60
# one record per distinct karana name (11), keyed by IAST, details from the SPEC row
kinfo = {}
for i, iast in enumerate(order):
    r = kar_spec[i]
    kinfo.setdefault(iast, dict(iast=iast, dev=r[1], fixed=r[3] == "Fixed", animal=r[4], nature=r[5],
                                use=r[6].replace("Avoid all", "avoid all")))
karana_names = list(kinfo.keys())
karana_order = [karana_names.index(n) for n in order]
vara = [dict(iast=v["iast"], ta=v["tamil"], lord=v["lord"], dev=vara_spec[i][1], en=vara_spec[i][3],
             nature=vara_spec[i][5]) for i, v in enumerate(names["vara"])]
rasi = [dict(iast=r["iast"], dev=r["devanagari"], month=r["tamil_month"], monthTa=r["tamil_month_script"])
        for r in names["rasi"]]
samvat = names["samvatsara"]
hora = names["hora_order_chaldean"]
kala = names["kala_eighth_parts_by_weekday"]
nature_uses = {k: dict(meaning=v["meaning"], uses=v["uses"]) for k, v in rules["nakshatra_natures"].items()}
wedding = rules["wedding"]
nak_by_iast = {n["iast"]: i for i, n in enumerate(names["nakshatra"])}
def fold(s):  # "Paṅguni" (rules.json) vs "Panguni" (names.json)
    import unicodedata
    return "".join(c for c in unicodedata.normalize("NFD", s) if not unicodedata.combining(c)).lower()


month_by_name = {fold(r["tamil_month"]): i for i, r in enumerate(names["rasi"])}
fest = []
for f in rules["festivals_solar_month_plus_star"]:
    m = f["month"].split(" (")[0]
    fest.append(dict(name=f["name"], month=month_by_name[fold(m)], star=nak_by_iast[f["nakshatra"]]))
wed_months = [month_by_name[fold(m)] for m in wedding["commonly_avoided_tamil_months"]]


grahas, rings = sky["graha"], sky["rings"]


def q(s):
    return json.dumps(s, ensure_ascii=False)


def kt_list(items, fn):
    return ",\n".join("        " + fn(x) for x in items)


header = "// GENERATED by scripts/gen_tables.py from data/names.json, data/rules.json and docs/SPEC.md §3.\n// Do not edit by hand; edit the sources and re-run the script.\n"

